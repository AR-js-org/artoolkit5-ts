import { createARToolKit, loadCameraFromUrl } from '@ar-js-org/artoolkit5-wasm';
import { ARToolKitCore, ARToolKitModule, ARToolKitState } from './domain';

/** Emscripten module extended with the bound C++ class constructor. */
interface ARToolKitModuleWithCore extends ARToolKitModule {
    ARToolKitCore: new () => ARToolKitCore;
}

/**
 * Initialises the WASM module, loads camera parameters and returns the state
 * object that every other operation in this library operates on.
 *
 * @param width  Frame width in pixels; must match the frames passed to `processFrame`.
 * @param height Frame height in pixels; must match the frames passed to `processFrame`.
 * @param cameraUrl URL of an ARToolKit `camera_para.dat` calibration file.
 * @param wasmUrl Optional explicit URL for `artoolkit5.wasm`. Required when the
 *   bundler rewrites asset paths, as Vite does.
 */
export async function createARToolKitState(
    width: number,
    height: number,
    cameraUrl: string,
    wasmUrl?: string
): Promise<ARToolKitState> {
    const artk = await createARToolKit({
        locateFile: (path: string) =>
            wasmUrl && path.endsWith('.wasm') ? wasmUrl : path,
    });

    // The loader types `mod` as `any`; narrow it once here so the rest of the
    // library is fully typed.
    const mod = artk.mod as ARToolKitModuleWithCore;
    const core = new mod.ARToolKitCore();

    const cameraId = await loadCameraFromUrl(mod, core, cameraUrl);
    await core.setup(width, height, cameraId);

    return {
        mod,
        core,
        width,
        height,
        patternMarkers: {},
        barcodeMarkers: {},
        minConfidence: { pattern: 0, barcode: 0 },
        disposed: false,
    };
}

/**
 * Releases the WASM resources held by a state.
 *
 * Call this when tracking stops — a single-page app that starts and stops AR,
 * or a test creating a state per case, otherwise leaks the C++ instance and its
 * heap allocations every time.
 *
 * One step, not two. `delete()` — generated by Embind rather than declared in
 * C++ — runs the C++ destructor, and `~ARToolKitCore()` calls `teardown()`
 * itself, so the handles are freed either way.
 *
 * This called `teardown()` first, on the belief that `delete()` alone would
 * leak them. That belief was wrong and the extra call aborted the module
 * (#90): `teardown()` ends with `arPattDeleteHandle(this->arPattHandle)` and
 * never nulls the member, so the destructor's pass hands the same freed
 * pointer back. `arPattDeleteHandle` does guard against `NULL` — but its
 * closing `pattHandle = NULL` assigns the parameter, not the caller's pointer,
 * so the guard cannot see a stale one. The second pass walks freed memory and
 * frees it again.
 *
 * Every other part of `teardown()` is idempotent, which is why only this one
 * bit.
 *
 * Scope of the damage, measured rather than assumed: the `abort()` destroys the
 * Emscripten module instance *that state belongs to*, and since
 * {@link createARToolKitState} instantiates a module per state, a subsequent
 * call still works. So an application that disposed and then created another
 * state kept running, which is why this survived a documented API with
 * lifecycle tests over it. What it did not survive is the dispose itself: a
 * `RuntimeError` out of a function whose whole job is cleanup, with the
 * instance's own deallocation left half-done, since `abort()` unwinds through
 * Embind's destructor before it releases the handle.
 *
 * The upstream fix is one line — null the member after freeing it, as
 * `deleteHandle()` already does for the other three — tracked as
 * artoolkit5-wasm#48. Calling `delete()` alone is correct regardless of
 * whether that lands, and works against every published 0.4.x.
 *
 * Safe to call more than once; subsequent calls do nothing. Every other
 * operation on the state throws {@link ARToolKitError} afterwards.
 */
export function disposeARToolKitState(state: ARToolKitState): void {
    if (state.disposed) {
        return;
    }

    // Not `teardown()` then `delete()`. See above: the pair double-frees
    // `arPattHandle` and aborts the module.
    state.core.delete();

    state.patternMarkers = {};
    state.barcodeMarkers = {};
    state.disposed = true;
}
